// Context holds package-reader state for one compiler frontend invocation.
// It is separate from the process-wide compiler state used by other packages.
type Context struct {
	Target         *ir.Package
	Inliner        *inline.Context
	timer          *base.Timings
	localPkgReader *pkgReader
	objReader      map[*types.Sym]pkgReaderIndex
	bodyReader     map[*ir.Func]pkgReaderIndex
	importBody     map[*types.Sym]pkgReaderIndex
	todoDicts      []func()
	todoBodies     []*ir.Func
	inlgen         int

	needWrapperTypes        []*types.Type
	haveWrapperTypes        []*types.Type
	needMethodValueWrappers []methodValueWrapper
	haveMethodValueWrappers []methodValueWrapper

	renameinitgen int

	dumpMu          sync.Mutex
	htmlDumpWriters map[*syntax.FuncDecl]*HTMLWriter
	htmlDumpFuncs   []*syntax.FuncDecl
}

func newContext(target *ir.Package, timer *base.Timings) *Context {
	if target.LocalPkg == nil {
		base.Fatalf("noder: target package has no local package")
	}
	if !target.AutoPos.IsKnown() && target.Ctxt != nil {
		posBase := src.NewFileBase("<autogenerated>", "<autogenerated>")
		target.AutoPos = target.Ctxt.PosTable.XPos(src.MakePos(posBase, 1, 0))
	}
	if !target.Pos.IsKnown() {
		target.Pos = target.AutoPos
	}
	if target.ShapePkg == nil {
		target.ShapePkg = target.Pkg("go.shape", "go.shape")
	}
	if target.GoPkg == nil {
		target.GoPkg = target.Pkg("go", "")
	}
	ctx := &Context{
		Target:     target,
		Inliner:    inline.NewContext(target),
		timer:      timer,
		objReader:  make(map[*types.Sym]pkgReaderIndex),
		bodyReader: make(map[*ir.Func]pkgReaderIndex),
		importBody: make(map[*types.Sym]pkgReaderIndex),
	}
	target.FrontendContext = ctx
	return ctx
}

// Renameinit returns a new package-local symbol for a generated init function.
func (c *Context) Renameinit() *types.Sym {
	s := c.Target.LocalPkg.LookupNum("init.", c.renameinitgen)
	c.renameinitgen++
	return s
}
